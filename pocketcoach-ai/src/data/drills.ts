/**
 * Drill library.
 *
 * Every drill is tagged with the *signals* it repairs, so the adaptive engine
 * can explain exactly why each drill was chosen for this athlete today.
 */
import type { DifficultyLevel, DrillDefinition, SportId } from '@/lib/types';

interface DrillOptions {
  /** stable id — defaults to a generated one, set it for drills the code refers to directly */
  id?: string;
  sport: SportId | 'any';
  skills?: string[];
  targetSignals: string[];
  targetLabel: string;
  difficulty: DifficultyLevel;
  durationMin: number;
  intensity: 1 | 2 | 3;
  equipment?: string[];
  setup: string;
  steps: string[];
  cue: string;
  volume: string;
}

let counter = 0;
function drill(name: string, o: DrillOptions): DrillDefinition {
  counter += 1;
  return {
    id: o.id ?? `drill-${String(counter).padStart(3, '0')}`,
    name,
    sport: o.sport,
    skills: o.skills,
    targetSignals: o.targetSignals,
    targetLabel: o.targetLabel,
    difficulty: o.difficulty,
    durationMin: o.durationMin,
    intensity: o.intensity,
    equipment: o.equipment ?? ['No equipment'],
    setup: o.setup,
    steps: o.steps,
    coachingCue: o.cue,
    volume: o.volume,
  };
}

