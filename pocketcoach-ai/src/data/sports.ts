/**
 * The PocketCoach rulebook.
 *
 * Adding a sport means adding one entry here — the analysis engine, the
 * overlay, the weakness report, the drill matcher and the adaptive planner all
 * read from these definitions, so nothing else has to change.
 */
import type { MeasureKey, MovementPhase, SignalDefinition, SkillDefinition, SportDefinition } from '@/lib/types';

interface SigOptions {
  unit: string;
  ideal: string;
  phase: MovementPhase;
  joints: string[];
  weight?: number;
  why: string;
  fix: string;
  params?: Record<string, number>;
}

function sig(key: string, label: string, measure: MeasureKey, o: SigOptions): SignalDefinition {
  return {
    key,
    label,
    measure,
    unit: o.unit,
    ideal: o.ideal,
    phase: o.phase,
    joints: o.joints,
    weight: o.weight ?? 1,
    whyItMatters: o.why,
    correction: o.fix,
    params: o.params,
  };
}

